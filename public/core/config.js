export function escapeHtml(value) {
    return String(value === undefined || value === null ? '' : value)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;');
}

export function getZodiac(num, year = 2026) {
    const map = CONFIG.zodiacMap[year] || CONFIG.zodiacMap[2026];
    const n = typeof num === 'number' ? num : parseInt(num, 10);
    if (isNaN(n) || n < 1) return map[0];
    return map[(n - 1) % 12];
}

export function getColor(numStr) {
    const pad = String(numStr).padStart(2, '0');
    if (CONFIG.colors.red.includes(pad)) return 'red';
    if (CONFIG.colors.blue.includes(pad)) return 'blue';
    return 'green';
}

export function getJiaYe(zodiac) {
    if (CONFIG.jiaYeMap.jia.includes(zodiac)) return 'jia';
    if (CONFIG.jiaYeMap.ye.includes(zodiac)) return 'ye';
    return 'unknown';
}

export function getHalfWaveKey(numStr) {
    const colorNames = { red: '红', blue: '蓝', green: '绿' };
    const color = getColor(numStr);
    const parity = parseInt(numStr, 10) % 2 === 0 ? '双' : '单';
    return `${colorNames[color]}${parity}`;
}

export function getHalfHeadKey(num) {
    const n = typeof num === 'number' ? num : parseInt(num, 10);
    const head = Math.floor(n / 10);
    const parity = n % 2 === 0 ? '双' : '单';
    return `${head}头${parity}`;
}

export function getSegmentKey(num) {
    const n = typeof num === 'number' ? num : parseInt(num, 10);
    const segment = Math.ceil(n / 7);
    const start = ((segment - 1) * 7 + 1).toString().padStart(2, '0');
    const end = Math.min(segment * 7, 49).toString().padStart(2, '0');
    return `${start}-${end}段`;
}

export function getRegionKey(num) {
    const n = typeof num === 'number' ? num : parseInt(num, 10);
    if (n >= 1 && n <= 10) return '一区(01-10)';
    if (n >= 11 && n <= 20) return '二区(11-20)';
    if (n >= 21 && n <= 30) return '三区(21-30)';
    if (n >= 31 && n <= 40) return '四区(31-40)';
    if (n >= 41 && n <= 49) return '五区(41-49)';
    return '一区(01-10)';
}

export function getRegionShortKey(num) {
    const n = typeof num === 'number' ? num : parseInt(num, 10);
    if (n >= 1 && n <= 10) return '1区';
    if (n >= 11 && n <= 20) return '2区';
    if (n >= 21 && n <= 30) return '3区';
    if (n >= 31 && n <= 40) return '4区';
    if (n >= 41 && n <= 49) return '5区';
    return '1区';
}
